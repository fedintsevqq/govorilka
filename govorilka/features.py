def _tuple(text: str) -> tuple[int, int, int]:
    return version.parse(text) or (0, 0, 0)


def guide_version() -> str:
    """Версия, от имени которой говорит окно. У пробных сборок номера нет: считаем их самой свежей версией из списка."""
    if version.is_release():
        return version.VERSION.lstrip("v")
    return max((f.since for f in FEATURES), key=_tuple)


def new_since(previous: str) -> list[Feature]:
    """Возможности, которых не было в версии previous."""
    base = _tuple(previous)
    return [f for f in FEATURES if _tuple(f.since) > base]


def render(feature: Feature, hotkey: str, dictation: str, mac: bool) -> dict[str, object]:
    """Возможность для окна: подставлены комбинации клавиш и слова под систему."""
    text = feature.body.format(
        hotkey=hotkey,
        dictation=dictation,
        copy="⌘C" if mac else "Ctrl+C",
        tray="строке меню" if mac else "трее",
    )
    return {"key": feature.key, "since": feature.since, "icon": feature.icon, "title": feature.title, "body": text}


def for_platform(items: list[Feature], mac: bool) -> list[Feature]:
    return [f for f in items if not (f.mac_only and not mac) and not (f.windows_only and mac)]
